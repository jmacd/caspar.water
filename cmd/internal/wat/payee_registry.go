package wat

import (
	"bytes"
	"errors"
	"fmt"
	"io"
	"os"
	"slices"
	"strings"

	"gopkg.in/yaml.v3"
)

type PayeeRecord struct {
	Name    string   `yaml:"name"`
	Aliases []string `yaml:"aliases,omitempty"`
}

type PayeeRegistry struct {
	Version int           `yaml:"version"`
	Payees  []PayeeRecord `yaml:"payees"`
	names   map[string]string
}

func payeeKey(name string) string {
	return strings.ToLower(strings.Join(strings.Fields(name), " "))
}

func (r *PayeeRegistry) validate(customers []string) error {
	if r.Version != 1 || r.Payees == nil {
		return fmt.Errorf("payee registry requires version 1 and a payees array")
	}
	r.names = make(map[string]string)
	owners := make(map[string]int)
	for i, record := range r.Payees {
		if !validPayeeName(record.Name) {
			return fmt.Errorf("invalid canonical payee name %q", record.Name)
		}
		seen := make(map[string]bool)
		for _, name := range append([]string{record.Name}, record.Aliases...) {
			if !validPayeeName(name) || !statementAccountHasIdentity(name) ||
				statementLabeledCheckNumber.MatchString(name) || statementCheckMetadata.MatchString(name) {
				return fmt.Errorf("invalid payee name or alias %q; check numbers are not identities", name)
			}
			if seen[name] {
				return fmt.Errorf("duplicate payee name or alias %q", name)
			}
			seen[name] = true
			key := payeeKey(name)
			if owner, ok := owners[key]; ok && owner != i {
				return fmt.Errorf("ambiguous payee name or alias %q: belongs to both %q and %q", name, r.Payees[owner].Name, record.Name)
			}
			owners[key], r.names[key] = i, record.Name
		}
	}
	for _, customer := range customers {
		if canonical, ok := r.names[payeeKey(customer)]; ok && canonical != customer {
			return fmt.Errorf("payee alias conflicts with customer name %q", customer)
		}
	}
	return nil
}

func decodePayeeRegistry(data []byte, customers []string) (*PayeeRegistry, error) {
	decoder := yaml.NewDecoder(bytes.NewReader(data))
	decoder.KnownFields(true)
	var registry PayeeRegistry
	if err := decoder.Decode(&registry); err != nil {
		return nil, fmt.Errorf("decode payee registry: %w", err)
	}
	var extra any
	if err := decoder.Decode(&extra); err != io.EOF {
		return nil, fmt.Errorf("payee registry must contain exactly one YAML document")
	}
	if err := registry.validate(customers); err != nil {
		return nil, err
	}
	return &registry, nil
}

func (r *PayeeRegistry) declarations() []string {
	var names []string
	for _, record := range r.Payees {
		names = append(names, record.Name)
		names = append(names, record.Aliases...)
	}
	slices.Sort(names)
	return slices.Compact(names)
}

func generatedPayees(cfg Config) []byte {
	var text strings.Builder
	text.WriteString(";; Generated by wat from payees.yaml. Do not edit.\n\n")
	for _, name := range cfg.payeeDeclarations {
		fmt.Fprintf(&text, "payee %s\n", name)
	}
	return []byte(text.String())
}

func InitPayeeRegistry(cfg Config) (string, error) {
	if _, err := os.Lstat(cfg.PayeeRegistryFile); !os.IsNotExist(err) {
		if err != nil {
			return "", err
		}
		return "", fmt.Errorf("payee registry %s: %w; will not overwrite", cfg.PayeeRegistryFile, os.ErrExist)
	}
	// Import the manual declarations, before enabling their generated replacement.
	cfg.PayeeRegistry = false
	books, err := Open(cfg)
	if err != nil {
		return "", err
	}
	draft, err := books.NewDraft()
	if err != nil {
		return "", err
	}
	files, err := books.run(cfg.Payees, "files")
	if err != nil {
		return "", err
	}
	for _, path := range strings.Split(strings.TrimSpace(files), "\n") {
		state, err := readNonsymlinkFileState(path, "payee declarations")
		if err != nil {
			return "", err
		}
		for _, line := range strings.Split(string(state.data), "\n") {
			line = strings.TrimSpace(line)
			if line != "" && !strings.HasPrefix(line, ";") && !strings.HasPrefix(line, "#") &&
				!strings.HasPrefix(line, "payee ") && !strings.HasPrefix(line, "include ") {
				return "", fmt.Errorf("payee import only supports declarations, includes and comments: %s", path)
			}
		}
	}
	text, err := books.run(cfg.Payees, "payees", "--declared")
	if err != nil {
		return "", err
	}
	registry := PayeeRegistry{Version: 1, Payees: []PayeeRecord{}}
	for _, name := range strings.Split(strings.TrimSpace(text), "\n") {
		if name != "" {
			registry.Payees = append(registry.Payees, PayeeRecord{Name: name})
		}
	}
	if err := registry.validate(books.Config.registryPayees); err != nil {
		return "", err
	}
	data, err := yaml.Marshal(registry)
	if err != nil {
		return "", err
	}
	if err := draft.unchanged(); err != nil {
		return "", err
	}
	state := draft.files[cfg.Payees]
	backup := cfg.Payees + ".pre-registry"
	if err := createExclusiveFile(backup, state.data); err != nil {
		return "", err
	}
	return backup, createExclusiveFile(cfg.PayeeRegistryFile, data)
}

func (b *Books) Payees() (*PayeeRegistry, error) {
	if err := b.checkInputs(); err != nil {
		return nil, err
	}
	if b.payeeRegistry == nil {
		return nil, fmt.Errorf("payee registry is disabled; run payee init and set payee_registry: true")
	}
	return decodePayeeRegistry(b.payeeRegistryState.data, b.Config.registryPayees)
}

func (b *Books) savePayees(registry *PayeeRegistry) (backup string, saved bool, err error) {
	if err := registry.validate(b.Config.registryPayees); err != nil {
		return "", false, err
	}
	data, err := yaml.Marshal(registry)
	if err != nil {
		return "", false, err
	}
	draft, err := b.NewDraft()
	if err != nil {
		return "", false, err
	}
	cfg := b.Config
	cfg.payeeDeclarations = registry.declarations()
	backup, saved, err = saveSingleFile(cfg.PayeeRegistryFile, b.payeeRegistryState, data, draft.unchanged, func() error {
		return draft.withProposedBooks(map[string][]byte{cfg.Payees: generatedPayees(cfg)}, b.checkSyntax)
	})
	if !saved {
		return backup, false, err
	}
	b.payeeRegistry = registry
	b.payeeRegistryState = fileState{data: data, mode: b.payeeRegistryState.mode}
	b.Config.payeeDeclarations = cfg.payeeDeclarations
	if generationErr := writeGeneratedFile(cfg.Payees, generatedPayees(cfg)); generationErr != nil {
		b.registryError = fmt.Errorf("payee registry saved, but declarations could not be generated; restart Wat: %w", generationErr)
		err = errors.Join(err, b.registryError)
	}
	return backup, true, err
}

func (b *Books) AddPayeeAlias(name, alias string) (string, bool, error) {
	registry, err := b.Payees()
	if err != nil {
		return "", false, err
	}
	for i := range registry.Payees {
		if registry.Payees[i].Name == name {
			registry.Payees[i].Aliases = append(registry.Payees[i].Aliases, alias)
			return b.savePayees(registry)
		}
	}
	return "", false, fmt.Errorf("unknown canonical payee %q", name)
}

func (b *Books) canonicalPayee(name string) string {
	if b.payeeRegistry != nil {
		if canonical, ok := b.payeeRegistry.names[payeeKey(name)]; ok {
			return canonical
		}
	}
	return name
}

func (b *Books) preferredPayees() ([]string, error) {
	names, err := b.declaredPayees()
	if err != nil {
		return nil, err
	}
	for i := range names {
		names[i] = b.canonicalPayee(names[i])
	}
	slices.Sort(names)
	return slices.Compact(names), nil
}

func (b *Books) canonicalTransactionPrompts() ([]StatementTransactionPrompt, error) {
	prompts := append([]StatementTransactionPrompt{}, b.Config.Statement.TransactionPrompts...)
	seen := make(map[string]bool)
	for i := range prompts {
		prompts[i].Payee = b.canonicalPayee(prompts[i].Payee)
		if seen[prompts[i].Payee] {
			return nil, fmt.Errorf("multiple transaction prompt rules resolve to canonical payee %q", prompts[i].Payee)
		}
		seen[prompts[i].Payee] = true
	}
	return prompts, nil
}

func (b *Books) canonicalDescription(description string) string {
	payee, memo, separated := strings.Cut(description, "|")
	canonical := b.canonicalPayee(strings.TrimSpace(payee))
	if canonical == strings.TrimSpace(payee) {
		return description
	}
	if separated {
		return canonical + " | " + strings.TrimSpace(memo)
	}
	return canonical
}

func (b *Books) payeeSearchText(description string) string {
	payee, _, _ := strings.Cut(description, "|")
	canonical := b.canonicalPayee(strings.TrimSpace(payee))
	text := description + " " + canonical
	if b.payeeRegistry != nil {
		for _, record := range b.payeeRegistry.Payees {
			if record.Name == canonical {
				text += " " + strings.Join(record.Aliases, " ")
				break
			}
		}
	}
	return payeeKey(text)
}
