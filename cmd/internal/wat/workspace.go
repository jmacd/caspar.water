package wat

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

const generatedHeader = ";; Generated by wat from wat.yaml. Do not edit.\n\n"

func prepareWorkspace(cfg Config) error {
	if err := ensureDirectory(filepath.Dir(cfg.Journal)); err != nil {
		return fmt.Errorf("prepare books directory: %w", err)
	}
	if err := ensureDirectory(cfg.Sources); err != nil {
		return fmt.Errorf("prepare sources directory: %w", err)
	}
	for _, journal := range cfg.writableJournals() {
		if err := ensureJournal(journal); err != nil {
			return err
		}
	}
	if err := writeGeneratedFile(cfg.LocalAccounts, generatedAccounts(cfg)); err != nil {
		return fmt.Errorf("generate local accounts: %w", err)
	}
	if err := writeGeneratedFile(cfg.Journal, generatedMaster(cfg)); err != nil {
		return fmt.Errorf("generate master journal: %w", err)
	}
	return nil
}

func readNonsymlinkFileState(path, label string) (fileState, error) {
	info, err := os.Lstat(path)
	if err != nil {
		return fileState{}, fmt.Errorf("%s: %w", label, err)
	}
	if !info.Mode().IsRegular() || info.Mode()&os.ModeSymlink != 0 {
		return fileState{}, fmt.Errorf("%s must be a nonsymlink regular file: %s", label, path)
	}
	real, err := filepath.EvalSymlinks(path)
	if err != nil {
		return fileState{}, fmt.Errorf("resolve %s: %w", label, err)
	}
	if filepath.Clean(real) != filepath.Clean(path) {
		return fileState{}, fmt.Errorf("%s must not traverse symlinks: %s", label, path)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return fileState{}, fmt.Errorf("read %s: %w", label, err)
	}
	return fileState{data: data, mode: info.Mode().Perm()}, nil
}

func generatedAccounts(cfg Config) []byte {
	var text strings.Builder
	text.WriteString(generatedHeader)
	text.WriteString("commodity $\n")
	if len(cfg.BankAccounts) != 0 {
		text.WriteString("account Bank  ; type: A\n")
	}
	for _, account := range cfg.Accounts {
		fmt.Fprintf(&text, "account %s\n", account)
	}
	for _, bank := range cfg.BankAccounts {
		fmt.Fprintf(&text, "account %s\n", bank.Account)
	}
	return []byte(text.String())
}

func generatedMaster(cfg Config) []byte {
	var text strings.Builder
	text.WriteString(generatedHeader)
	fmt.Fprintf(&text, "include %s\n", accountsJournal)
	fmt.Fprintf(&text, "include %s\n", manualJournal)
	for _, bank := range cfg.BankAccounts {
		fmt.Fprintf(&text, "include %s\n", filepath.Base(bank.Journal))
	}
	return []byte(text.String())
}

func ensureDirectory(path string) error {
	info, err := os.Lstat(path)
	switch {
	case os.IsNotExist(err):
		return os.Mkdir(path, 0700)
	case err != nil:
		return err
	case !info.IsDir() || info.Mode()&os.ModeSymlink != 0:
		return fmt.Errorf("%s must be a nonsymlink directory", path)
	default:
		return nil
	}
}

func ensureJournal(path string) error {
	info, err := os.Lstat(path)
	switch {
	case os.IsNotExist(err):
		file, createErr := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600)
		if createErr != nil {
			return fmt.Errorf("create journal %s: %w", path, createErr)
		}
		if closeErr := file.Close(); closeErr != nil {
			return fmt.Errorf("create journal %s: %w", path, closeErr)
		}
		return syncDirectory(filepath.Dir(path))
	case err != nil:
		return err
	case !info.Mode().IsRegular() || info.Mode()&os.ModeSymlink != 0:
		return fmt.Errorf("journal must be a nonsymlink regular file: %s", path)
	default:
		return nil
	}
}

func writeGeneratedFile(path string, data []byte) (err error) {
	if current, readErr := os.ReadFile(path); readErr == nil && bytes.Equal(current, data) {
		return nil
	}
	if info, statErr := os.Lstat(path); statErr == nil {
		if !info.Mode().IsRegular() || info.Mode()&os.ModeSymlink != 0 {
			return fmt.Errorf("generated journal must be a nonsymlink regular file: %s", path)
		}
	} else if !os.IsNotExist(statErr) {
		return statErr
	}
	temporary, err := os.CreateTemp(filepath.Dir(path), ".wat-generate-")
	if err != nil {
		return err
	}
	tempPath := temporary.Name()
	if closeErr := temporary.Close(); closeErr != nil {
		return closeErr
	}
	defer func() {
		if removeErr := os.Remove(tempPath); removeErr != nil && !os.IsNotExist(removeErr) {
			err = errors.Join(err, removeErr)
		}
	}()
	if err := writeSynced(tempPath, data, 0600); err != nil {
		return err
	}
	if err := os.Rename(tempPath, path); err != nil {
		return err
	}
	return syncDirectory(filepath.Dir(path))
}
