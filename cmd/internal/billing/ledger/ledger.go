const cycleDateLayout = "2006-01"

// Inputs names the authoritative CSV sources for a historical migration.
type Inputs struct {
	UsersFile    string
	BusinessFile string
	CyclesFile   string
	PaymentsFile string
}

// CycleSummary contains the source-to-journal reconciliation totals.
type CycleSummary struct {
	Name        string
	Expenses    int64
	Assessments int64
	Payments    int64
	Unassigned  int64
}

// Result is a complete migration assembled in memory before any files are
// written.
type Result struct {
	Files  map[string][]byte
	Cycles []CycleSummary
}

type cycleData struct {
	cycle       expense.Cycle
	name        string
	sourceRow   int
	assessments []assessment.Assessment
	unassigned  currency.Amount
	payments    []indexedPayment
}

type indexedPayment struct {
	payment   payment.Payment
	sourceRow int
}

type journalEntry struct {
	date  time.Time
	order int
	key   string
	text  string
}

// Generate validates and converts the CSV sources without modifying fs.
func Generate(inputs Inputs, fs afero.Fs) (*Result, error) {
	users, err := csv.ReadFile[user.User](inputs.UsersFile, fs)
	if err != nil {
		return nil, err
	}
	if err := validateUsers(users); err != nil {
		return nil, err
	}

	companies, err := csv.ReadFile[business.Business](inputs.BusinessFile, fs)
	if err != nil {
		return nil, err
	}
	if len(companies) != 1 {
		return nil, fmt.Errorf("business file must contain exactly one row, got %d", len(companies))
	}

	cycles, err := csv.ReadFile[expense.Cycle](inputs.CyclesFile, fs)
	if err != nil {
		return nil, err
	}
	if err := validateCycleSequence(cycles); err != nil {
		return nil, err
	}
	if err := expense.SplitAnnual(cycles); err != nil {
		return nil, fmt.Errorf("split annual expenses: %w", err)
	}

	cycleRecords := make([]cycleData, len(cycles))
	for i, cycle := range cycles {
		name := cycle.PeriodStart.Closing().Date().Format(cycleDateLayout)
		allocation, err := assessment.Allocate(users, cycle)
		if err != nil {
			return nil, fmt.Errorf("cycle %s assessments: %w", name, err)
		}
		cycleRecords[i] = cycleData{
			cycle:       cycle,
			name:        name,
			sourceRow:   i + 2,
			assessments: allocation.Assessments,
			unassigned:  allocation.Unassigned,
		}
	}

	payments, err := csv.ReadFile[payment.Payment](inputs.PaymentsFile, fs)
	if err != nil {
		return nil, err
	}
	if err := assignPayments(users, payments, cycleRecords); err != nil {
		return nil, err
	}

	files := map[string][]byte{
		"accounts.journal": renderAccounts(companies[0], users),
		"books.journal": []byte(
			"; Generated by ledger-migrate. Do not edit generated history.\n" +
				"include accounts.journal\n" +
				"include cycles/*.journal\n",
		),
	}
	result := &Result{Files: files}
	for _, record := range cycleRecords {
		content, summary := renderCycle(record)
		files[filepath.ToSlash(filepath.Join("cycles", record.name+".journal"))] = content
		result.Cycles = append(result.Cycles, summary)
	}
	return result, nil
}

// Write writes a generated result to a new directory. Existing paths are
// refused so a migration cannot silently mix with or overwrite prior output.
func Write(outputDir string, result *Result, fs afero.Fs) error {
	if outputDir == "" {
		return fmt.Errorf("output directory is empty")
	}
	if _, err := fs.Stat(outputDir); err == nil {
		return fmt.Errorf("output path already exists: %s", outputDir)
	} else if !os.IsNotExist(err) {
		return fmt.Errorf("inspect output path %s: %w", outputDir, err)
	}

	names := make([]string, 0, len(result.Files))
	for name := range result.Files {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		target := filepath.Join(outputDir, filepath.FromSlash(name))
		if err := fs.MkdirAll(filepath.Dir(target), 0o755); err != nil {
			return fmt.Errorf("create output directory for %s: %w", target, err)
		}
		if err := afero.WriteFile(fs, target, result.Files[name], 0o644); err != nil {
			return fmt.Errorf("write %s: %w", target, err)
		}
	}
	return nil
}

func validateUsers(users []user.User) error {
	if len(users) == 0 {
		return fmt.Errorf("users file contains no customers")
	}
	seen := make(map[string]struct{}, len(users))
	for _, customer := range users {
		name := customer.AccountName
		if strings.TrimSpace(name) != name || strings.ContainsAny(name, ":\r\n;") {
			return fmt.Errorf("account name %q is not safe as a Ledger account component", name)
		}
		if _, ok := seen[name]; ok {
			return fmt.Errorf("duplicate customer account name: %s", name)
		}
		seen[name] = struct{}{}
	}
	return nil
}

func validateCycleSequence(cycles []expense.Cycle) error {
	if len(cycles) == 0 {
		return fmt.Errorf("cycles file contains no billing cycles")
	}
	if cycles[0].PeriodStart.Starting().Date().Month() != time.October {
		return fmt.Errorf(
			"first historical cycle must start in October so annual expenses split correctly",
		)
	}
	seen := make(map[string]struct{}, len(cycles))
	for i, cycle := range cycles {
		start := cycle.PeriodStart.Starting().Date()
		close := cycle.PeriodStart.Closing().Date()
		name := close.Format(cycleDateLayout)
		if _, ok := seen[name]; ok {
			return fmt.Errorf("duplicate cycle close name: %s", name)
		}
		seen[name] = struct{}{}
		if i == 0 {
			continue
		}
		expected := cycles[i-1].PeriodStart.Closing().Date().AddDate(0, 0, 1)
		if !start.Equal(expected) {
			return fmt.Errorf(
				"cycle %s starts %s; expected contiguous start %s",
				name,
				start.Format("2006-01-02"),
				expected.Format("2006-01-02"),
			)
		}
	}
	return nil
}

func assignPayments(users []user.User, payments []payment.Payment, cycles []cycleData) error {
	knownUsers := make(map[string]struct{}, len(users))
	for _, customer := range users {
		knownUsers[customer.AccountName] = struct{}{}
	}
	seen := make(map[string]struct{}, len(payments))
	for i, item := range payments {
		if _, ok := knownUsers[item.AccountName]; !ok {
			return fmt.Errorf("payment row %d references unknown account %q", i+2, item.AccountName)
		}
		if item.Amount.Units() <= 0 {
			return fmt.Errorf("payment row %d must be positive", i+2)
		}
		key := fmt.Sprintf(
			"%s\x00%s\x00%d\x00%s",
			item.Date.Date().Format("2006-01-02"),
			item.AccountName,
			item.Amount.Units(),
			item.Comments,
		)
		if _, ok := seen[key]; ok {
			return fmt.Errorf("duplicate payment row %d for account %q", i+2, item.AccountName)
		}
		seen[key] = struct{}{}

		assigned := false
		for cycleNo := range cycles {
			start := cycles[cycleNo].cycle.PeriodStart.Starting().Date()
			close := cycles[cycleNo].cycle.PeriodStart.Closing().Date()
			date := item.Date.Date()
			if !date.Before(start) && !date.After(close) {
				cycles[cycleNo].payments = append(cycles[cycleNo].payments, indexedPayment{
					payment:   item,
					sourceRow: i + 2,
				})
				assigned = true
				break
			}
		}
		if !assigned {
			return fmt.Errorf(
				"payment row %d dated %s is outside historical cycle coverage",
				i+2,
				item.Date.Date().Format("2006-01-02"),
			)
		}
	}
	return nil
}

func renderAccounts(company business.Business, users []user.User) []byte {
	var out bytes.Buffer
	fmt.Fprintln(&out, "; Generated by ledger-migrate. Do not edit generated history.")
	fmt.Fprintf(&out, "; Entity: %s\n", commentText(company.Name))
	fmt.Fprintf(&out, "; Address: %s\n", commentText(company.Address.OneLine()))
	fmt.Fprintf(&out, "; Contact: %s\n\n", commentText(company.Contact))
	fmt.Fprintln(&out, "commodity $")
	fmt.Fprintln(&out, "  format $1,000.00")
	fmt.Fprintln(&out)

	for _, account := range []string{
		"Assets",
		"Assets:Bank",
		"Assets:Accounts Receivable",
		"Income",
		"Income:Water Service",
		"Expenses",
		"Expenses:Operations",
		"Expenses:Utilities",
		"Expenses:Insurance",
		"Expenses:Taxes",
	} {
		fmt.Fprintf(&out, "account %s\n", account)
	}

	customers := append([]user.User(nil), users...)
	sort.Slice(customers, func(i, j int) bool {
		return customers[i].AccountName < customers[j].AccountName
	})
	for _, customer := range customers {
		fmt.Fprintf(
			&out,
			"account Assets:Accounts Receivable:%s  ; customer: %s\n",
			customer.AccountName,
			commentText(customer.UserName),
		)
	}
	return out.Bytes()
}

func renderCycle(record cycleData) ([]byte, CycleSummary) {
	closeDate := record.cycle.PeriodStart.Closing().Date()
	var entries []journalEntry

	expenseTotal := currency.Sum(
		record.cycle.Operations,
		record.cycle.Utilities,
		record.cycle.Insurance,
		record.cycle.Taxes,
	).Units()
	var expenseEntry bytes.Buffer
	fmt.Fprintf(&expenseEntry, "%s * Cycle expenses %s\n", closeDate.Format("2006-01-02"), record.name)
	fmt.Fprintf(&expenseEntry, "    ; source: cycles.csv:%d\n", record.sourceRow)
	appendPosting(&expenseEntry, "Expenses:Operations", record.cycle.Operations.Units())
	appendPosting(&expenseEntry, "Expenses:Utilities", record.cycle.Utilities.Units())
	appendPosting(&expenseEntry, "Expenses:Insurance", record.cycle.Insurance.Units())
	appendPosting(&expenseEntry, "Expenses:Taxes", record.cycle.Taxes.Units())
	appendPosting(&expenseEntry, "Assets:Bank", -expenseTotal)
	entries = append(entries, journalEntry{
		date: closeDate, order: 1, key: "expenses", text: expenseEntry.String(),
	})

	var assessmentTotal int64
	for _, item := range record.assessments {
		if item.Amount.IsZero() {
			continue
		}
		assessmentTotal += item.Amount.Units()
		var entry bytes.Buffer
		fmt.Fprintf(&entry, "%s * Water service assessment\n", closeDate.Format("2006-01-02"))
		fmt.Fprintf(&entry, "    ; cycle: %s\n", record.name)
		fmt.Fprintf(&entry, "    ; customer-account: %s\n", item.User.AccountName)
		appendPosting(
			&entry,
			"Assets:Accounts Receivable:"+item.User.AccountName,
			item.Amount.Units(),
		)
		appendPosting(&entry, "Income:Water Service", -item.Amount.Units())
		entries = append(entries, journalEntry{
			date: closeDate, order: 2, key: item.User.AccountName, text: entry.String(),
		})
	}

	var paymentTotal int64
	for _, indexed := range record.payments {
		item := indexed.payment
		paymentTotal += item.Amount.Units()
		var entry bytes.Buffer
		fmt.Fprintf(&entry, "%s * Payment received\n", item.Date.Date().Format("2006-01-02"))
		fmt.Fprintf(&entry, "    ; source: payments.csv:%d\n", indexed.sourceRow)
		fmt.Fprintf(&entry, "    ; customer-account: %s\n", item.AccountName)
		if item.Comments != "" {
			fmt.Fprintf(&entry, "    ; comments: %s\n", commentText(item.Comments))
		}
		appendPosting(&entry, "Assets:Bank", item.Amount.Units())
		appendPosting(
			&entry,
			"Assets:Accounts Receivable:"+item.AccountName,
			-item.Amount.Units(),
		)
		entries = append(entries, journalEntry{
			date: item.Date.Date(), order: 0, key: fmt.Sprintf("%09d", indexed.sourceRow), text: entry.String(),
		})
	}

	sort.Slice(entries, func(i, j int) bool {
		if !entries[i].date.Equal(entries[j].date) {
			return entries[i].date.Before(entries[j].date)
		}
		if entries[i].order != entries[j].order {
			return entries[i].order < entries[j].order
		}
		return entries[i].key < entries[j].key
	})

	var out bytes.Buffer
	fmt.Fprintln(&out, "; Generated by ledger-migrate. Do not edit generated history.")
	fmt.Fprintf(
		&out,
		"; Billing cycle %s through %s\n\n",
		record.cycle.PeriodStart.Starting().Date().Format("2006-01-02"),
		closeDate.Format("2006-01-02"),
	)
	if !record.unassigned.IsZero() {
		fmt.Fprintf(
			&out,
			"; Historical unbilled effective-connection shares: %s\n\n",
			ledgerAmount(record.unassigned.Units()),
		)
	}
	for _, entry := range entries {
		fmt.Fprintln(&out, entry.text)
	}
	return out.Bytes(), CycleSummary{
		Name:        record.name,
		Expenses:    expenseTotal,
		Assessments: assessmentTotal,
		Payments:    paymentTotal,
		Unassigned:  record.unassigned.Units(),
	}
}

func appendPosting(out *bytes.Buffer, account string, cents int64) {
	if cents == 0 {
		return
	}
	fmt.Fprintf(out, "    %-56s %s\n", account, ledgerAmount(cents))
}

func ledgerAmount(cents int64) string {
	sign := ""
	if cents < 0 {
		sign = "-"
		cents = -cents
	}
	return fmt.Sprintf("$%s%d.%02d", sign, cents/100, cents%100)
}

func commentText(value string) string {
	return strings.Join(strings.Fields(value), " ")
}
